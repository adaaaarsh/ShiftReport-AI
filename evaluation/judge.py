"""LLM-as-judge on free endpoints. Every report is scored by every judge in models.json.

The judges never see which model or prompt version produced a report. The primary judge
(Gemini 3.5 Flash Lite) comes from a different family than all three generators and scores
all reports, as does the secondary judge (Gemma 4 31B). GPT-OSS-120B scores only the
human-rated sample, to check whether a judge favours reports from its own family.

Usage:
    export GEMINI_API_KEY=...  GROQ_API_KEY=...
    python judge.py                       # all judges, all reports
    python judge.py --judges gemini:gemini-3.6-flash
Output: outputs/judge/<judge>/<report>.json
"""
import argparse, json
from typing import Literal
from pydantic import BaseModel, Field, ValidationError
from providers import CONFIG, ROOT, Caller, DailyLimitReached, slug, strip_reasoning


class IssueCheck(BaseModel):
    key_ref: str = Field(description="The answer-key ref this check is about, copied exactly")
    reported: bool = Field(description="Does the report contain an entry for this issue?")
    machine_handling: Literal["correct_id", "wrong_id", "flagged_ambiguous_or_unrecognized", "guessed_specific_id", "not_reported"] = Field(
        description="correct_id: matches key ID. guessed_specific_id: key is AMBIGUOUS/UNRECOGNIZED but the report asserts one registry ID without flagging doubt.")
    severity_given: Literal["CRITICAL", "HIGH", "MEDIUM", "LOW", "UNKNOWN", "NONE"]
    facts_captured: int = Field(description="How many of the key's facts appear in the report")
    missing_flagged: int = Field(description="How many of the key's 'missing' items the report explicitly flags as unknown or needing clarification")


class Judgement(BaseModel):
    issues: list[IssueCheck]
    contradictions_flagged: int = Field(description="How many of the key's contradictions the report explicitly points out")
    distractors_reported_as_issues: int = Field(description="How many key distractors were wrongly turned into equipment issues")
    fabricated_details: list[str] = Field(description="Each specific detail in the report not stated in or directly implied by the input (times, shift letters, actions, causes, machine IDs, people). Placeholders like 'Not specified' are not fabrications.")
    accuracy: int = Field(ge=1, le=5)
    completeness: int = Field(ge=1, le=5)
    severity: int = Field(ge=1, le=5)
    readability: int = Field(ge=1, le=5)
    uncertainty: int = Field(ge=1, le=5)
    rationale: str = Field(description="2-4 sentences justifying the rubric scores")


SCHEMA = {"type": "json_schema", "json_schema": {"name": "judgement", "schema": Judgement.model_json_schema()}}


REGISTRY = "\n".join(f"- {e['id']}: {e['name']} ({e['line']})" for e in json.loads((ROOT / "equipment.json").read_text()))


def build_prompt(rubric, scenario, report):
    return f"""You are evaluating a manufacturing shift-handover report generated from a supervisor's informal notes.
You do not know which system or prompt produced it. Be strict and literal: only the supervisor input counts as evidence.

The report writer had access to this plant equipment registry, so registry IDs, names and lines are legitimate
when they correctly match what the supervisor referred to (a wrong match is an accuracy error, not a fabrication):
<registry>
{REGISTRY}
</registry>

Report template fields are NOT fabrications: the report date, "Shift: Not specified", "Prepared by: Floor Supervisor",
section headings, severity labels, and a "Report generated by ShiftReport AI" footer. Everything else that is not
stated in or directly implied by the supervisor input IS a fabrication, including invented units, causes, actions,
outcomes, monitoring steps, and claims such as "no safety incidents" that the supervisor did not make.

<rubric>
{rubric}
</rubric>

<supervisor_input>
{scenario['input']}
</supervisor_input>

<answer_key>
{json.dumps(scenario['key'], indent=1)}
</answer_key>

<report>
{report}
</report>

Return JSON matching the schema: one IssueCheck per answer-key issue in key order, then the scenario-level counts, the fabricated details, and the five rubric scores."""


def judge_one(caller, prompt):
    msgs = [{"role": "user", "content": prompt}]
    for attempt in range(3):
        resp = caller.chat(msgs, temperature=0, response_format=SCHEMA)
        raw = strip_reasoning(resp.choices[0].message.content)
        raw = raw.removeprefix("```json").removeprefix("```").removesuffix("```").strip()
        try:
            return Judgement.model_validate_json(raw)
        except ValidationError as e:
            msgs = msgs[:1] + [{"role": "assistant", "content": raw},
                               {"role": "user", "content": f"That JSON did not validate: {e.errors()[:3]}. Return corrected JSON only."}]
    raise RuntimeError("judge returned invalid JSON 3 times")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--judges", nargs="*")
    ap.add_argument("--all", action="store_true", help="secondary judges score every report, not just the human sample")
    args = ap.parse_args()
    rubric = (ROOT / "rubric.md").read_text()
    scenarios = {s["id"]: s for s in json.loads((ROOT / "scenarios.json").read_text())["scenarios"]}
    reports = sorted((ROOT / "outputs" / "reports").glob("*.md"))
    from make_scoring_sheet import human_sample
    sample = {f"{sid}_{v}_{m}_r1" for sid, v, m in human_sample()}
    for jspec in [j for j in CONFIG["judges"] if not args.judges or j["id"] in args.judges]:
        caller = Caller(jspec)
        # Free-tier daily caps: secondary judges score only the 120 human-rated reports.
        todo = reports if jspec.get("scope") == "all" or args.all else [p for p in reports if p.stem in sample]
        out = ROOT / "outputs" / "judge" / slug(jspec["id"]); out.mkdir(parents=True, exist_ok=True)
        try:
            for p in todo:
                dest = out / f"{p.stem}.json"
                if dest.exists():
                    continue
                try:
                    j = judge_one(caller, build_prompt(rubric, scenarios[p.stem.split("_")[0]], p.read_text()))
                except RuntimeError as e:
                    print(f"  skip {p.name}: {e}"); continue
                dest.write_text(j.model_dump_json(indent=1))
                print(f"[{slug(jspec['id'])}] {p.name}: A{j.accuracy} C{j.completeness} S{j.severity} R{j.readability} U{j.uncertainty}")
        except DailyLimitReached as e:
            print(f"STOPPED {jspec['id']}: {e}")


if __name__ == "__main__":
    main()
